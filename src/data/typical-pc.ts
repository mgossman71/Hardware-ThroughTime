/**
 * Nearest typical-PC entry for a given year — the picker "snaps" to these
 * milestone years rather than inventing a config for every single year.
 * Ties (e.g. 1980 between 1979 and 1981) resolve to the LATER year.
 */
export function typicalPcForYear(year: number): TypicalPc {
  return TYPICAL_PCS.reduce(
    (best, pc) => (Math.abs(pc.year - year) <= Math.abs(best.year - year) ? pc : best),
    TYPICAL_PCS[0],
  );
}